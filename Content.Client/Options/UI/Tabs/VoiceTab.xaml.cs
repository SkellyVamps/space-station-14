using Content.Client.Voice;
using Content.Shared.CCVar;
using Content.Shared.Input;
using Content.Shared.Radio;
using Robust.Client.AutoGenerated;
using Robust.Client.Input;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client.Options.UI.Tabs;

/// <summary>
/// Voice chat settings: connecting the microphone (voice webpage or app), push to talk / voice activation, volumes,
/// and hearing yourself.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class VoiceTab : Control
{
    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private Robust.Shared.Network.IClientNetManager _net = default!;
    [Dependency] private IEntityManager _entMan = default!;
    [Dependency] private IInputManager _input = default!;
    [Dependency] private IPrototypeManager _proto = default!;

    private VoiceTransmitSystem? _transmit;
    private VoiceExternalSystem? _external;

    public VoiceTab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _entMan.TrySystem(out _transmit);
        _entMan.TrySystem(out _external);

        ExternalOpenButton.OnPressed += _ => _external?.OpenWebpage();
        ExternalCopyButton.OnPressed += _ =>
        {
            _external?.CopyLink();
            ExternalCopyButton.Text = Loc.GetString("ui-options-voice-external-copied");
        };
        ExternalDisconnectButton.OnPressed += _ => _external?.Disconnect();

        Control.AddOptionCheckBox(CCVars.VoiceClientEnabled, EnabledCheckBox);

        Control.AddOptionDropDown(CCVars.VoiceInputMode, DropDownInputMode, new[]
        {
            new OptionDropDownCVar<int>.ValueOption((int) VoiceInputMode.PushToTalk, Loc.GetString("ui-options-voice-mode-ptt")),
            new OptionDropDownCVar<int>.ValueOption((int) VoiceInputMode.VoiceActivation, Loc.GetString("ui-options-voice-mode-vad")),
        });

        Control.AddOption(new OptionSliderFloatCVar(Control, _cfg, CCVars.VoiceActivationThreshold,
            SliderActivationThreshold, -70f, -10f, 1f, FormatDb));
        Control.AddOptionSlider(CCVars.VoiceActivationRelease, SliderActivationRelease, 100, 1500, FormatMs);

        var channels = BuildRadioChannelOptions();
        Control.AddOptionDropDown(CCVars.VoiceRadioKey2Channel, DropDownRadioKey2, channels);
        Control.AddOptionDropDown(CCVars.VoiceRadioKey3Channel, DropDownRadioKey3, channels);
        Control.AddOptionDropDown(CCVars.VoiceRadioKey4Channel, DropDownRadioKey4, channels);

        Control.AddOptionPercentSlider(CCVars.VoiceOutputVolume, SliderOutputVolume, 0f, 2f);
        Control.AddOptionPercentSlider(CCVars.VoiceRadioVolume, SliderRadioVolume, 0f, 2f);
        Control.AddOptionSlider(CCVars.VoiceJitterBufferMs, SliderJitterBuffer, 20, 300, FormatMs);
        Control.AddOption(new OptionSliderFloatCVar(Control, _cfg, CCVars.VoiceDucking,
            SliderDucking, 0f, 0.9f, 0.05f, FormatOffPercent));
        Control.AddOptionCheckBox(CCVars.VoiceShowIndicators, IndicatorsCheckBox);
        Control.AddOptionCheckBox(CCVars.VoiceShowRangeCircle, RangeCircleCheckBox);
        Control.AddOptionCheckBox(CCVars.VoiceShowRadioPanel, RadioPanelCheckBox);

        Control.Initialize();

        RadioPanelResetButton.OnPressed += _ =>
        {
            _cfg.SetCVar(CCVars.VoiceRadioPanelPosition, string.Empty);
            _cfg.SaveToFile();
        };

        MicTestButton.OnToggled += args =>
        {
            if (_transmit == null)
                return;

            if (args.Pressed)
                _transmit.StartTest();
            else
                _transmit.StopTest();
        };
    }

    private static string FormatDb(OptionSliderFloatCVar _, float value) => $"{value:0} dB";

    private static string FormatMs(OptionSliderIntCVar _, int value) => $"{value} ms";

    private static string FormatOffPercent(OptionSliderFloatCVar _, float value)
    {
        return value < 0.01f ? Loc.GetString("ui-options-voice-off") : $"{value * 100:0}%";
    }

    /// <summary>
    /// Every radio channel, by name. Players only transmit on the ones their character actually has.
    /// </summary>
    private List<OptionDropDownCVar<string>.ValueOption> BuildRadioChannelOptions()
    {
        var options = new List<OptionDropDownCVar<string>.ValueOption>
        {
            new(string.Empty, Loc.GetString("ui-options-voice-radio-key-unset")),
        };

        var channels = new List<RadioChannelPrototype>(_proto.EnumeratePrototypes<RadioChannelPrototype>());
        channels.Sort((a, b) => string.Compare(a.LocalizedName, b.LocalizedName, StringComparison.CurrentCultureIgnoreCase));
        foreach (var channel in channels)
        {
            options.Add(new OptionDropDownCVar<string>.ValueOption(channel.ID, channel.LocalizedName));
        }

        return options;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!VisibleInTree || _transmit == null || _external == null)
            return;

        // How loud the server is getting you, while you talk or test.
        LevelMeter.Value = _external.Talking ? _external.Level : 0f;
        MicTestButton.Disabled = !_external.Connected && !MicTestButton.Pressed;

        StatusLabel.Text = GetStatus();

        UpdateExternal();

        // Only meaningful (and only accurate) while connected: it's the server's setting.
        TranscribeNotice.Visible = _net.IsConnected && _cfg.GetCVar(CCVars.VoiceTranscribe);

        var pttKey = _input.TryGetKeyBinding(ContentKeyFunctions.VoicePushToTalk, out var binding)
            ? binding.GetKeyString()
            : Loc.GetString("ui-options-voice-unbound");
        var radioKey = _input.TryGetKeyBinding(ContentKeyFunctions.VoiceRadioPushToTalk, out var radioBinding)
            ? radioBinding.GetKeyString()
            : Loc.GetString("ui-options-voice-unbound");
        PushToTalkHint.Text = Loc.GetString("ui-options-voice-ptt-hint", ("key", pttKey), ("radioKey", radioKey));
    }

    private void UpdateExternal()
    {
        if (_external is not { Available: true })
        {
            ExternalStatus.Text = Loc.GetString("ui-options-voice-external-status-not-in-game");
            ExternalOpenButton.Visible = false;
            ExternalCopyButton.Visible = false;
            ExternalDisconnectButton.Visible = false;
            return;
        }

        ExternalCopyButton.Visible = true;

        ExternalStatus.Text = !_external.Connected
            ? Loc.GetString("ui-options-voice-external-status-off")
            : Loc.GetString(_external.Kind == "app"
                ? "ui-options-voice-external-status-app"
                : "ui-options-voice-external-status-web");
        ExternalDisconnectButton.Visible = _external.Connected;
        ExternalOpenButton.Visible = !_external.Connected;
    }

    private string GetStatus()
    {
        if (!_cfg.GetCVar(CCVars.VoiceEnabled))
            return Loc.GetString("ui-options-voice-status-server-disabled");

        if (_transmit!.AdminMuted)
            return Loc.GetString("ui-options-voice-status-admin-muted");

        if (_external is not { Connected: true })
            return Loc.GetString("ui-options-voice-status-no-microphone");

        return Loc.GetString("ui-options-voice-status-capturing", ("device", Loc.GetString(_external.Kind == "app"
            ? "ui-options-voice-device-app"
            : "ui-options-voice-device-web")));
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        // Never leave the microphone looping back after the options window closes.
        if (MicTestButton.Pressed)
        {
            MicTestButton.Pressed = false;
            _transmit?.StopTest();
        }
    }
}
